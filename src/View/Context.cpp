Context::Context(ContextInit_t ctxInit)
{
    this->originX = ctxInit.originX;
    this->originY = ctxInit.originY;
    this->dimHeight = ctxInit.dimHeight;
    this->dimWidth = ctxInit.dimWidth;
}

Context::~Context()
{
}

// --------------------------------------------------------------------------------
//      Heritage Methods
